"""spectrum.py: a RADIAL SPECTRUM, one ring of 64 per video frame -> src/v/spec.js (Ra 10/2: "draw a mental circle, then
put frequencies along the circle with distance from the center corresponding with volume… ideally the guy's voice on one
side and the girl's on the other").
Ring index j ↔ angle j/64·2π (0 = right, counter-clockwise, y up):
  top half (j 0..31, angles 0..π): the VOCAL stem, 110–420 Hz (the sung fundamentals: measured, the tenor sits ~150 Hz, the alto ~265), high
  frequencies on the right, low on the left: the tenor lands left, the alto right;
  bottom half (j 32..63, angles π..2π): the INSTRUMENTAL stem, 40–6000 Hz, low on the left, high on the right.
Volume = dB above each stem's floor, 0..1 over 42 dB; fast attack, ~0.25 s release, so it pulses rather than flickers.
Run with ../pbloom_mv/.venv/bin/python analysis/spectrum.py"""
import base64, numpy as np, librosa
SR, FPS = 22050, 30
def ring(path, fmin, fmax, n=32, rng=42):
    y, _ = librosa.load(path, sr=SR, mono=True)
    S = np.abs(librosa.stft(y, n_fft=4096, hop_length=SR // FPS, center=True)) ** 2
    f = librosa.fft_frequencies(sr=SR, n_fft=4096); edges = np.geomspace(fmin, fmax, n + 1)
    B = np.stack([S[(f >= edges[i]) & (f < edges[i + 1])].mean(0) for i in range(n)])   # bands × frames
    db = 10 * np.log10(B + 1e-12); top = np.percentile(db, 99.7)
    v = np.clip((db - (top - rng)) / rng, 0, 1)
    out = np.zeros_like(v); r = np.exp(-1 / (FPS * .25))                                  # release ~0.25 s
    for t in range(v.shape[1]): out[:, t] = np.maximum(v[:, t], out[:, t - 1] * r if t else 0)
    return out
voc = ring('analysis/stems/htdemucs/track/vocals.wav', 110, 420, rng=56)   # wider: the opening tenor is quiet
ins = ring('analysis/stems/htdemucs/track/no_vocals.wav', 40, 6000)
n = min(voc.shape[1], ins.shape[1]); R = np.zeros((n, 64), np.uint8)
R[:, :32] = (voc[::-1, :n].T * 255).astype(np.uint8)          # j 0 (right) = high … j 31 (left) = low
R[:, 32:] = (ins[:, :n].T * 255).astype(np.uint8)             # j 32 (left) = low … j 63 (right) = high
b64 = base64.b64encode(R.tobytes()).decode()
open('src/v/spec.js', 'w').write("// generated by analysis/spectrum.py: a radial spectrum, 64 per frame (top = vocals low→left, bottom = instruments), 0..255\n"
  f"const SPEC = (() => {{ const s = atob('{b64}'), a = new Uint8Array(s.length); for (let i = 0; i < s.length; i++) a[i] = s.charCodeAt(i); return {{ fps: {FPS}, n: 64, data: a }}; }})();\n")
for t in [18, 19.5, 25, 50, 52, 85, 110, 116, 119, 188]:
    i = int(t * FPS); top = R[i, :32].astype(int); print(t, 'vocal peak at j', int(top.argmax()), '(0 = right/high, 31 = left/low), level', top.max())
