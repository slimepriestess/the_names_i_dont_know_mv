"""lyric_align.py: per-word lyric times, corrected (Ra 10/2: the lyrics ran ~2 s ahead of the voice).
Whisper stamps the first word of a phrase from the end of the previous one, absorbing the silence before it (the opening
"I" lasts 16.74–18.02). So: (1) every word longer than 0.45 s gets its start moved to where the vocal stem's energy actually
rises inside it; (2) the lyric sheet (src/v/texts.js) is aligned to whisper's words by sequence matching; unmatched sheet
words (the bridge's other languages) are interpolated. -> src/v/lyrtimes.js: LYRT = [[t0, t1, [[word, t], ...]], ...]
Run with ../pbloom_mv/.venv/bin/python analysis/lyric_align.py"""
import json, re, difflib, numpy as np, librosa
y, sr = librosa.load('analysis/stems/htdemucs/track/vocals.wav', sr=22050, mono=True)
H = 110; rms = librosa.feature.rms(y=y, frame_length=882, hop_length=H)[0]; tt = np.arange(len(rms)) * H / sr
env = np.convolve(rms, np.ones(5) / 5, mode='same')
W = [w for w in json.load(open('analysis/words.json')) if w['e'] - w['s'] > .03]   # whisper's zero-length echoes (a doubled "I've got a stranger's hands" at 87.62) are junk
moved = []
for w in W:
    if w['e'] - w['s'] > .45:
        a, b = np.searchsorted(tt, w['s']), np.searchsorted(tt, w['e'])
        seg = env[a:b]
        if len(seg) > 4:
            lo, hi = seg.min(), seg.max(); k = np.argmax(seg > lo + .35 * (hi - lo))
            ns = min(tt[a + k], w['e'] - .12)
            if ns - w['s'] > .08: moved.append((w['w'], round(w['s'], 2), round(ns, 2))); w['s'] = float(ns)
src = open('src/v/texts.js').read()
body = src[src.index('lyrics: [') + len('lyrics: '):]; body = body[:body.index(']],') + 2]
L = json.loads(re.sub(r',(\s*[\]}])', r'\1', body))
norm = lambda s: re.sub(r"[^a-z0-9']", '', s.lower().replace('’', "'"))
sheet = [(li, wd) for li, (_, _, txt) in enumerate(L) for wd in txt.split()]
A = [norm(wd) for _, wd in sheet]; Bw = [norm(w['w']) for w in W]
t_of = [None] * len(sheet)
for blk in difflib.SequenceMatcher(None, A, Bw, autojunk=False).get_matching_blocks():
    for k in range(blk.size): t_of[blk.a + k] = W[blk.b + k]['s']
# fill unmatched: within a line, between known neighbours, else spread across the line's whisper window
for li, (a0, a1, txt) in enumerate(L):
    idx = [k for k, (l, _) in enumerate(sheet) if l == li]
    known = [(k, t_of[k]) for k in idx if t_of[k] is not None and a0 - 1 <= t_of[k] <= a1 + 1]
    for k in idx:
        if t_of[k] is not None and a0 - 1 <= t_of[k] <= a1 + 1: continue
        before = [(kk, t) for kk, t in known if kk < k]; after = [(kk, t) for kk, t in known if kk > k]
        lo = before[-1] if before else (idx[0] - 1, a0); hi = after[0] if after else (idx[-1] + 1, a1 - .2)
        t_of[k] = lo[1] + (hi[1] - lo[1]) * (k - lo[0]) / max(1, hi[0] - lo[0])
out = []
for li, (a0, a1, txt) in enumerate(L):
    ws = [[sheet[k][1], round(float(t_of[k]), 2)] for k in range(len(sheet)) if sheet[k][0] == li]
    for i in range(1, len(ws)): ws[i][1] = max(ws[i][1], ws[i - 1][1] + .05)
    out.append([ws[0][1], a1, ws])
open('src/v/lyrtimes.js', 'w').write('// generated by analysis/lyric_align.py: [line start, line end, [[word, start s], ...]] (onset-corrected)\nconst LYRT = ' + json.dumps(out, ensure_ascii=False) + ';\n')
print(len(moved), 'word starts moved; biggest:', sorted(moved, key=lambda m: m[1] - m[2])[:8])
for (a0, a1, txt), o in zip(L, out):
    if o[0] - a0 > .3: print(f'{a0:7.2f} -> {o[0]:7.2f}  {txt[:40]}')
