"""tokens.py: real BPE token boundaries for every string the beam writes with ticks (Whisper's multilingual
tokenizer, a GPT-2-family byte-level BPE, from the local HF cache) -> src/v/tokens.js
Run with ../pbloom_mv/.venv/bin/python analysis/tokens.py"""
import glob, json
from tokenizers import Tokenizer
tk = Tokenizer.from_file(glob.glob('/Users/stellarashtra/.cache/huggingface/hub/models--Systran--faster-whisper-large-v3/snapshots/*/tokenizer.json')[0])
S = ["the following is a transcript—", "edit, thanks for the gold, kind stranger", "Il était une fois",
     "preheat the oven to 350", "if anyone finds this, tell my mother", "¿alguien sigue leyendo esto?", "lol same",
     "Ich weiß nicht, wem ich es sonst sagen soll", "I don't know who else to tell", "おやすみなさい", "Chapter One",
     "спокойной ночи", "sorry for formatting, on mobile", "je t'aime", "I love you"]
out = {}
for s in S:
    e = tk.encode(s, add_special_tokens=False)
    cuts = sorted({b for a, b in e.offsets if 0 < b < len(s)})                  # char offsets where one token ends
    out[s] = cuts
open('src/v/tokens.js', 'w').write("// generated by analysis/tokens.py: token boundaries (char offsets) per string, Whisper's BPE\nconst TOKCUTS = " + json.dumps(out, ensure_ascii=False) + ";\n")
print({k: len(v) + 1 for k, v in out.items()})
