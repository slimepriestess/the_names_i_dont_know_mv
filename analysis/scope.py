"""scope.py: a radial oscilloscope, one ring per video frame -> src/scope.js.

Ra: "explore incorporating a radial oscilloscope for the spike shape motion... if there's motion on the scope there
should be motion on screen". For each frame (30 fps): a window of the mix around that instant, low-passed so the ring
reads as shapes rather than hash, triggered on a rising zero crossing (a real scope's trigger: holds the shape still
when the sound is steady), resampled to N points around the circle, its ends blended so the ring closes, and scaled
by loudness^0.5 so the quiet opening still visibly moves. Int8 values, base64.
Run with ../pbloom_mv/.venv/bin/python analysis/scope.py
"""
import base64, numpy as np, librosa, scipy.signal as sg
SR, FPS, N, WIN = 22050, 30, 64, 1400
y, _ = librosa.load('track.wav', sr=SR, mono=True)
b, a = sg.butter(3, 900 / (SR / 2)); yl = sg.filtfilt(b, a, y)
rms = librosa.feature.rms(y=y, frame_length=2048, hop_length=SR // FPS)[0]
rms = rms / np.percentile(rms, 99.5)
nf = int(len(y) / SR * FPS); out = np.zeros((nf, N), np.int8)
for i in range(nf):
    c = int(i / FPS * SR); seg = yl[max(0, c - WIN):c + WIN]
    if len(seg) < 2 * WIN: continue
    zc = np.where((seg[:-1] < 0) & (seg[1:] >= 0))[0]                          # trigger: the rising crossing nearest the middle
    z = zc[np.argmin(np.abs(zc - WIN // 2))] if len(zc) else WIN // 2
    w = seg[z:z + WIN]
    if len(w) < WIN: w = seg[:WIN]
    w = w / (np.max(np.abs(w)) + 1e-9)                                         # shape from the window, size from loudness
    ring = np.interp(np.linspace(0, WIN - 1, N), np.arange(WIN), w)
    ring = ring - np.linspace(ring[0], ring[-1], N) * 0                         # (kept for clarity: closure below)
    k = np.linspace(0, 1, N); ring = ring - (ring[-1] - ring[0]) * k            # close the ring: ends meet
    amp = np.sqrt(min(1., rms[min(i, len(rms) - 1)]))
    out[i] = np.clip(ring * amp * 127, -127, 127).astype(np.int8)
b64 = base64.b64encode(out.tobytes()).decode()
open('src/scope.js', 'w').write(
    "// generated by analysis/scope.py: a radial oscilloscope, N values per video frame (Int8, base64)\n"
    f"const SCOPE = (() => {{ const s = atob('{b64}'), a = new Int8Array(s.length); for (let i = 0; i < s.length; i++) a[i] = s.charCodeAt(i) << 24 >> 24; return {{ fps: {FPS}, n: {N}, data: a }}; }})();\n")
print('frames', nf, 'bytes', out.size, 'nonzero frames', int((np.abs(out).max(1) > 4).sum()))
