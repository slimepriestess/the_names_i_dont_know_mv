"""force_align.py: per-word lyric times by FORCED ALIGNMENT (torchaudio MMS_FA, a CTC aligner) of the lyric sheet against the
demucs vocal stem, section by section. Ra 10/2: whisper's times ran a word early on the syncopated lines ("after" shown on
"closing"; "every" at 0:24, sung at 0:26). Whisper recognises; this aligns known text. Lines in non-Latin scripts (and any
the aligner can't place) keep the onset-corrected whisper times from lyric_align.py.
-> src/v/lyrtimes.js (same format). Run with ../pbloom_mv/.venv/bin/python analysis/force_align.py"""
import json, re, unicodedata, torch, torchaudio
from torchaudio.pipelines import MMS_FA as bundle
model = bundle.get_model(); tok = bundle.get_tokenizer(); aligner = bundle.get_aligner()
import librosa; wav = torch.from_numpy(librosa.load('analysis/stems/htdemucs/track/vocals.wav', sr=16000, mono=True)[0]).unsqueeze(0)
src = open('src/v/lyrtimes.js').read(); OLD = json.loads(src[src.index('const LYRT = ') + 13:src.rindex(';')])     # whisper-based fallback
norm = lambda w: re.sub(r"[^a-z']", '', unicodedata.normalize('NFKD', w.lower().replace('’', "'")).encode('ascii', 'ignore').decode())
# 166-177 (the repeated 'I love you') squeezes under the aligner: whisper's onset-corrected times are kept there
SECT = [(14, 47.5), (47, 77.2), (76.5, 108), (108, 138.2), (138, 166.5), (176.6, 213.5), (213.5, 239.9)]
new = [[l[0], l[1], [list(w) for w in l[2]]] for l in OLD]
for a, b in SECT:
    lines = [i for i, l in enumerate(OLD) if a <= l[2][0][1] < b]
    words = [(i, k, norm(w)) for i in lines for k, (w, _) in enumerate(OLD[i][2])]
    words = [x for x in words if x[2]]
    if not words: continue
    seg = wav[:, int(a * 16000):int(b * 16000)]
    with torch.inference_mode(): em, _ = model(seg)
    try: spans = aligner(em[0], tok([w for _, _, w in words]))
    except Exception as e: print('section', a, b, 'failed:', e); continue
    ratio = seg.shape[1] / em.shape[1] / 16000
    for (i, k, w), sp in zip(words, spans):
        t0 = a + sp[0].start * ratio; new[i][2][k][1] = round(t0, 2)
    print(f'section {a:6.1f}-{b:6.1f}: {len(words)} words aligned')
# pinned: "je t'aime, je t'aime" (whisper mis-heard the French; the aligner, run over 166-177, placed it cleanly before
# squeezing the "I love you"s that follow)
for l in new:
    if l[2][0][0] == 'je': l[2] = [['je', 167.02], ["t'aime,", 167.24], ['je', 168.87], ["t'aime", 169.07]]
for l in new:
    for k in range(1, len(l[2])): l[2][k][1] = max(l[2][k][1], l[2][k - 1][1] + .05)
    l[0] = l[2][0][1]
open('src/v/lyrtimes.js', 'w').write('// generated by analysis/force_align.py: [line start, line end, [[word, start s], ...]] (MMS forced alignment on the vocal stem)\nconst LYRT = ' + json.dumps(new, ensure_ascii=False) + ';\n')
for o, n in zip(OLD[:8], new[:8]): print(' '.join(f'{w}@{t}' for w, t in n[2]), ' | was', ' '.join(f'{t}' for w, t in o[2]))
