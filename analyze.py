"""Audio curves + timing for the renderer -> src/feat.js, src/timing.js, src/lyrics.js.

feat.js: 60 Hz 0..1 curves. vox = vocal-stem loudness, loud = full-mix loudness, low/high = instrumental band energy,
air = 6k+ energy of the vocal (the alto's shimmer). timing.js: tracked beats (a hymn breathes, so these drift; use them
for pulses, not for cuts). lyrics.js: whisper's lines and words from analysis/ (asr.py on the demucs vocal stem).
Run with ../pbloom_mv/.venv/bin/python (hymn_mv copy of orange_hat_mv/analyze.py).
"""
import json
import numpy as np
import librosa

SR, RATE = 22050, 60
HOP = SR // RATE
ST = "analysis/stems/htdemucs/track"
mix, _ = librosa.load("track.wav", sr=SR, mono=True)
voc, _ = librosa.load(f"{ST}/vocals.wav", sr=SR, mono=True)
ins, _ = librosa.load(f"{ST}/no_vocals.wav", sr=SR, mono=True)
n = len(mix) // HOP
fix = lambda a: librosa.util.fix_length(np.asarray(a, dtype=float), size=n)

def norm(x, lo=3, hi=99.5):
    a, b = np.percentile(x, lo), np.percentile(x, hi)
    return np.clip((x - a) / (b - a + 1e-9), 0, 1)

def smooth(x, k):
    w = np.hanning(k); return np.convolve(x, w / w.sum(), mode="same")

vdb = 20 * np.log10(librosa.feature.rms(y=voc, hop_length=HOP)[0] + 1e-6)
S = np.abs(librosa.stft(ins, n_fft=2048, hop_length=HOP)); f = librosa.fft_frequencies(sr=SR, n_fft=2048)
band = lambda Sx, lo, hi: norm(smooth(20 * np.log10(Sx[(f >= lo) & (f < hi)].mean(0) + 1e-6), 9), 5, 99.5)
SV = np.abs(librosa.stft(voc, n_fft=2048, hop_length=HOP))
out = dict(
    vox=fix(np.clip((vdb + 42) / 30, 0, 1)),
    loud=fix(norm(smooth(20 * np.log10(librosa.feature.rms(y=mix, hop_length=HOP)[0] + 1e-6), 15), 5, 99.5)),
    low=fix(band(S, 30, 200)), high=fix(band(S, 3000, 10000)), air=fix(band(SV, 6000, 11000)),
)
js = "// generated by analyze.py\nconst FEAT = {rate: %.5f,\n" % (SR / HOP)
for k, v in out.items():
    js += f"{k}: new Uint8Array([{','.join(str(int(round(x * 255))) for x in v)}]),\n"
open("src/feat.js", "w").write(js + "};\n")

tempo, bt = librosa.beat.beat_track(y=mix, sr=SR, hop_length=512, units="time")
beats = [round(float(b), 3) for b in bt]
open("src/timing.js", "w").write(
    "// generated by analyze.py: tracked beats (s). A hymn breathes: use these for pulses, not cuts.\n"
    f"const BEATS = {json.dumps(beats)};\n")

lines = []
for ln in open("analysis/asr_lines.txt"):
    p = ln.split(None, 2)
    if len(p) == 3: lines.append([float(p[0]), float(p[1]), p[2].strip()])
words = [[w["s"], w["e"], w["w"]] for w in json.load(open("analysis/words.json"))]
open("src/lyrics.js", "w").write(
    "// generated by analyze.py from analysis/asr_lines.txt + words.json (whisper on the vocal stem; the bridge's\n"
    "// non-English lines are mis-transcribed, their times are right). LINES = [t0, t1, text], WORDS = [t0, t1, word].\n"
    f"const LINES = {json.dumps(lines, ensure_ascii=False)};\nconst WORDS = {json.dumps(words, ensure_ascii=False)};\n")
print("frames", n, "tempo", np.round(tempo, 1), "beats", len(beats), "lines", len(lines), "words", len(words))
